// 조회된 지정명 목록으로 도시 유형을 점수화한다.
function analyzeLaw(names) {
  const score = { A: 0, B: 0, C: 0, D: 0, E: 0 };
  const basis = [];
  const zones = ZONES.filter((z) => names.includes(z[0]));
  zones.forEach(([n, def, bcr, far, pts]) => {
    Object.entries(pts).forEach(([k, v]) => (score[k] += v));
    basis.push({ cite: "시행령 제30·84·85조", title: n,
      text: `${def}. 건폐율 ${bcr}% 이하, 용적률 ${far[0]}~${far[1]}% 이하(상한 범위, 조례로 더 낮게 정함)`, basis: "법령" });
  });
  CONSTRAINTS.forEach((c) => {
    const hit = names.filter((n) => c.re.test(n));
    if (!hit.length) return;
    Object.entries(c.adj).forEach(([k, v]) => (score[k] += v));
    basis.push({ cite: c.cite, title: hit[0], text: c.text, basis: c.basis });
  });
  NOTES.forEach((nt) => {
    const hit = names.filter((n) => nt.re.test(n));
    if (hit.length) basis.push({ cite: "계획 시 참고", title: hit[0], text: nt.text, basis: "지침" });
  });
  const ranked = Object.entries(score).sort((a, b) => b[1] - a[1]).map(([k, v]) => ({ key: k, score: v, ...TYPES[k] }));
  return { ranked, basis, hasZone: zones.length > 0 };
}
